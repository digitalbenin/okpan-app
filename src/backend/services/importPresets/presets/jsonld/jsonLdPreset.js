/**
 * JSON-LD import preset
 *
 * FORMAT RECOGNITION
 * Auto-detection requires format === 'json'. The file is then inspected by
 * `isJsonLdShape`, which walks the value recursively (handling bare arrays and
 * nested objects) and returns true as soon as it finds any of the four
 * canonical JSON-LD keywords: `@context`, `@id`, `@type`, or `@graph`.
 *
 * PARSING PROCEDURE
 * `extractJsonLdProjection` (jsonLdTriples.js) drives the conversion:
 *   1. Unwrap — the top-level value is unwrapped via `extractEntityCollection`:
 *      bare arrays, `@graph` containers and `@set` containers are all normalised
 *      to a flat list of entity objects; a plain object becomes a single-item list.
 *   2. Project — each entity is passed to `projectEntity`, which iterates its
 *      keys and maps them to a flat row:
 *        • `@id` and `@type` are stored directly under those keys.
 *        • Scalar predicates (strings, numbers, booleans) and values that
 *          JSON-LD already flattens to strings (`@value`, `@id` refs, `@list`,
 *          `@set`) are stored at the predicate key.
 *        • Object-valued predicates are dot-path expanded. When the items share
 *          a property with unique single-string values that property is used as a
 *          key selector (`predicate[keyProp=val].subProp`); otherwise a flat
 *          merge is produced (`predicate.subProp`).
 *   3. Multi-values — `appendValue` accumulates repeated values as arrays;
 *      `finalizeRow` converts single-element arrays back to plain strings.
 *
 * OUTPUT
 * Returns `{ data, tabularized, prefilledMapping, warnings }`:
 *   • `data`            — array of flat row objects (one per JSON-LD entity).
 *   • `tabularized`     — always true.
 *   • `prefilledMapping`— generated by `buildPrefilledMapping` using `@id` as
 *                         the primary column hint.
 *   • `warnings`        — human-readable notes; parsing errors are caught and
 *                         surfaced here rather than thrown, so a malformed file
 *                         never crashes the import pipeline.
 */
import { extractJsonLdProjection, isJsonLdShape } from './jsonLdTriples.js';

const jsonLdPreset = {
  id: 'json-ld',
  label: 'JSON-LD',
  description: 'Builds subject-centered import rows from raw JSON-LD structure without ontology-specific field guesses.',
  supportedFormats: ['json'],

  canAutoDetect({ format, data }) {
    if (format !== 'json') return false;
    return isJsonLdShape(data);
  },

  // Projects JSON-LD subjects into flat rows; returns an empty-data result if nothing was extracted
  // and wraps all parsing in an error boundary so a malformed file surfaces as a warning rather than a crash
  parse({ data }) {
    try {
      const { rows, prefilledMapping, warnings } = extractJsonLdProjection(data);

      if (!rows.length) {
        return {
          data: [],
          tabularized: true,
          prefilledMapping: [],
          warnings: ['No JSON-LD subjects were projected into import rows.', ...warnings]
        };
      }

      return {
        data: rows,
        tabularized: true,
        prefilledMapping,
        warnings: [
          'JSON-LD parser applied: raw subject-predicate-object structure was projected into subject-centered import rows.',
          ...warnings
        ]
      };
    } catch (error) {
      const message = error instanceof Error ? error.message : 'Unknown JSON-LD parsing error';

      return {
        data: [],
        tabularized: true,
        prefilledMapping: [],
        warnings: [`JSON-LD parser failed: ${message}`]
      };
    }
  }
};

export default jsonLdPreset;